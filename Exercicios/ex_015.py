valor_a = int(input('Insira um valor numérico\n-->'))
valor_b = int(input('Insira outro valor numérico\n-->'))

print('O resultado da soma é', valor_a + valor_b)
print('O resultado da subtração é', valor_a - valor_b)
print('O resultado da multiplicação é', valor_a * valor_b)
print('O resultado da divisão é', valor_a / valor_b)
print('O resto do resultado é', valor_a % valor_b)